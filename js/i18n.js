function aplicarTraducao(lang) {
    const dict = translations[lang] || translations['pt-BR'];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        if (dict[el.getAttribute('data-i18n')]) {
            el.textContent = dict[el.getAttribute('data-i18n')];
        }
    });

    document.documentElement.lang = lang;
    localStorage.setItem('idiomaSelecionado', lang);

    document.querySelectorAll('.lang-flag').forEach(f => f.classList.remove('active'));
    const flagAtiva = document.querySelector(`.lang-flag[data-lang="${lang}"]`);
    if (flagAtiva) flagAtiva.classList.add('active');

    // Atualiza as frases do efeito de digitação (variável global do main.js)
    if (dict.typing_phrases) {
        window.phrases = dict.typing_phrases;
        window.phraseIndex = 0;
        window.charIndex = 0;
        window.isDeleting = false;
    }
}

document.addEventListener('DOMContentLoaded', () => {
    const idiomaSalvo = localStorage.getItem('idiomaSelecionado') || 'pt-BR';
    aplicarTraducao(idiomaSalvo);

    document.querySelectorAll('.lang-flag').forEach(flag => {
        flag.addEventListener('click', () => aplicarTraducao(flag.getAttribute('data-lang')));
    });
});